def cut(key):
    source = Image.open(HERE/'aligned'/f'{key}.png').convert('RGBA')
    mask = Image.new('L',(W*3,H*3))
    ImageDraw.Draw(mask).polygon([(x*3,y*3) for x,y in POLYGONS[key]],fill=255)
    mask = mask.resize((W,H),Image.Resampling.LANCZOS)
    pixels = np.array(source)
    # 根据实际原画手部皮肤连通区域保留指尖和描线，避免手工边界削掉拳头外缘。
    rgb=pixels[:,:,:3].astype(np.int16)
    r,g,b=rgb[:,:,0],rgb[:,:,1],rgb[:,:,2]
    skin=((r>b+12)&(r>g+5)&(g>b-2)&(r>170)&(pixels[:,:,3]>100)).astype(np.uint8)
    count,labels,stats,centers=cv2.connectedComponentsWithStats(skin)
    point=np.array(HAND_CENTERS[key])
    candidates=[i for i in range(1,count) if 100<stats[i,4]<1500 and stats[i,1]>=315 and stats[i,1]<485]
    chosen=min(candidates,key=lambda i:float(np.sum((centers[i]-point)**2)))
    outline=cv2.dilate((labels==chosen).astype(np.uint8)*255,np.ones((5,5),np.uint8))
    matte=np.maximum(np.array(mask),outline)
    pixels[:,:,3] = (pixels[:,:,3].astype(np.uint16)*matte//255).astype(np.uint8)
    pixels[pixels[:,:,3]<8]=0
    layer = Image.fromarray(pixels)
    # 生成图使用画面左侧手臂；整数像素镜像映射到人物右肩，不拉伸、旋转肢体。
    layer=layer.transform((W,H),Image.Transform.AFFINE,(-1,0,566,0,1,0),Image.Resampling.NEAREST)
    # 所有新原画统一校准到原人物手臂比例；逐帧使用同一比例，绝不按关节变形。
    scale=.90; px,py=320,382
    return layer.convert('RGBa').transform((W,H),Image.Transform.AFFINE,
        (1/scale,0,px-px/scale,0,1/scale,py-py/scale),Image.Resampling.BICUBIC).convert('RGBA')


def main():
    target = HERE/'cels'; target.mkdir(exist_ok=True)
    order = ['rest'] + [f'raise-{i:02}' for i in [1,2,4,3,5,6,7]]
    order += [f'peak-{i:02}' for i in range(8)]
    order += [f'lower-{i:02}' for i in range(1,8)] + ['rest']
    rest = Image.open(ROOT/'extra-gestures/layers/idea-right-00.png').convert('RGBA')
    body = Image.open(ROOT/'extra-gestures/layers/idea-body.png').convert('RGBA')
    canvas = Image.new('RGB',(6*288,4*330),'#ebe4f2')
    preview=[]; entries=[]
    for i,key in enumerate(order):
        layer = rest if key=='rest' else cut(key)
        filename=f'{i:02}.png'; layer.save(target/filename)
        composite=Image.alpha_composite(body,layer)
        thumbnail=composite.resize((288,312),Image.Resampling.LANCZOS)
        canvas.paste(thumbnail,((i%6)*288,(i//6)*330+16),thumbnail)
        ImageDraw.Draw(canvas).text(((i%6)*288+8,(i//6)*330+2),f'{i:02}: {key}',fill='#51425d')
        preview.append(thumbnail)
        entries.append({'file':'cels/'+filename,'source':key,'sha256':hashlib.sha256((target/filename).read_bytes()).hexdigest()})
    canvas.save(HERE/'cels-contact.png')
    preview[0].save(HERE/'direct-preview.webp',save_all=True,append_images=preview[1:],duration=83,loop=0,quality=94,method=0)
    metadata={'name':'idea','size':[W,H],'method':'individually drawn cels; polygon cutouts; integer-pixel mirroring; no limb deformation',
              'mirror_x':283,'uniform_scale':.90,'scale_pivot':[320,382],
              'body_sha256':hashlib.sha256((ROOT/'extra-gestures/layers/idea-body.png').read_bytes()).hexdigest(),
              'frames':entries,'polygons':POLYGONS}
    (HERE/'metadata.json').write_text(json.dumps(metadata,ensure_ascii=False,indent=2),encoding='utf-8')

if __name__=='__main__': main()
