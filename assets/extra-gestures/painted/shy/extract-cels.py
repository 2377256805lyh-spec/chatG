def mask(points):
    im=Image.new('L',(SIZE[0]*3,SIZE[1]*3))
    ImageDraw.Draw(im).polygon([(round(x*3),round(y*3)) for x,y in points],fill=255)
    return im.resize(SIZE,Image.Resampling.LANCZOS)

def arm(side,name):
    if name=='rest':
        return Image.open(ROOT.parent.parent/'layers'/f'shy-{side}-00.png').convert('RGBA')
    im=Image.open(ROOT/'aligned'/f'{name}.png').convert('RGBA')
    from PIL import ImageChops,ImageFilter
    import numpy as np
    # 肤色区域补全手指/前臂，避免手工轮廓误切细小的手缘；不移动任何像素。
    a=np.asarray(im).astype('int16')
    skin=(a[:,:,0]>170)&(a[:,:,1]>100)&(a[:,:,2]<240)&(a[:,:,0]-a[:,:,1]>6)&(a[:,:,0]-a[:,:,2]>15)&(a[:,:,3]>128)
    allowed=Image.new('L',SIZE)
    bounds=(180,365,290,478) if side=='left' else (290,365,380,488)
    is_peak = (side=='left' and name in ['07','08','09','10','11','12','13','14']) or (side=='right' and name in ['09','10','11','12','13','14','15','16'])
    if is_peak:
        bounds=(210,336,253,452) if side=='left' else (299,336,345,452)
    if name=='neck-00' and side=='left': bounds=(218,347,255,463)
    ImageDraw.Draw(allowed).rectangle(bounds,fill=255)
    skin=ImageChops.multiply(Image.fromarray((skin*255).astype('uint8')),allowed).filter(ImageFilter.MaxFilter(5))
    region=ImageChops.lighter(mask((LEFT if side=='left' else RIGHT)[name]),skin)
    # 只保护原脸部轮廓，手仍能位于两侧头发前方；不作水平截断。
    original=np.asarray(Image.open(ROOT.parent.parent/'layers'/'shy-body.png').convert('RGBA')).astype('int16')
    face_skin=(original[:,:,0]>170)&(original[:,:,1]>100)&(original[:,:,2]<240)&(original[:,:,0]-original[:,:,1]>6)&(original[:,:,0]-original[:,:,2]>15)&(original[:,:,3]>128)
    profile=[]
    for y in range(330,361):
        xs=np.flatnonzero(face_skin[y,205:351])+205
        if len(xs): profile.append((y,int(xs.min())-2,int(xs.max())+2))
    face=mask([(left,y) for y,left,right in profile]+[(right,y) for y,left,right in reversed(profile)])
    region=ImageChops.multiply(region,ImageChops.invert(face))
    # 颈窝固定色块不属于任何手臂；这块区域不与选定的手势前景重叠。
    ImageDraw.Draw(region).rectangle((264,355,289,380),fill=0)
    im.putalpha(ImageChops.multiply(im.getchannel('A'),region))
    return im

def main():
    out=ROOT/'cels';out.mkdir(exist_ok=True)
    body=Image.open(ROOT.parent.parent/'layers'/'shy-body.png').convert('RGBA')
    previews=[];cells=[]
    for i,(left,right) in enumerate(TIMELINE):
        cel=Image.new('RGBA',SIZE);cel.alpha_composite(arm('left',left));cel.alpha_composite(arm('right',right));cel.save(out/f'{i:02}.png')
        composite=body.copy();composite.alpha_composite(cel);previews.append(composite)
        cells.append({'file':f'{i:02}.png','left':left,'right':right,'translation':[0,0],'warping':False})
    previews[0].save(ROOT/'preview.webp',save_all=True,append_images=previews[1:],duration=83,loop=0,quality=94,method=0,alpha_quality=100)
    contact=Image.new('RGB',(576*4,624*6),'#ddd4e7');d=ImageDraw.Draw(contact)
    for i,im in enumerate(previews):
        x,y=(i%4)*576,(i//4)*624;contact.paste(im,(x,y),im);d.text((x+10,y+10),str(i),fill='black')
    contact.resize((1152,1872),Image.Resampling.LANCZOS).save(ROOT/'cel-review.png')
    for batch in range(2):
        detail=Image.new('RGB',(416*4,312*3),'#ddd4e7');dd=ImageDraw.Draw(detail)
        for j,im in enumerate(previews[batch*12:batch*12+12]):
            x,y=(j%4)*416,(j//4)*312
            part=im.crop((170,330,378,486)).resize((416,312),Image.Resampling.LANCZOS)
            detail.paste(part,(x,y),part);dd.text((x+8,y+8),str(batch*12+j),fill='black')
        detail.save(ROOT/f'arm-detail-{batch}.png')
    (ROOT/'metadata.json').write_text(json.dumps({'size':SIZE,'method':'manual polygon cutouts of painted poses; no joint warping','head_protection':'original face scanline contour occludes generated jaw colors; hands remain in front of side hair','cells':cells,'left_masks':LEFT,'right_masks':RIGHT},ensure_ascii=False,indent=2),encoding='utf8')

